@pytest.mark.parametrize("status,expected", [(422, 2), (409, 1), (403, 1)])
def test_registered_refusal_only_422_gets_one_repairable_followup(monkeypatch, status, expected):
    calls = []
    secret = "private-test-hub-password"
    monkeypatch.setenv("HUB_SECRET", secret)
    def request(method, url, **kwargs):
        calls.append(kwargs["json"])
        if len(calls) == 1:
            return SimpleNamespace(status_code=status, json=lambda: {"detail": "\ud800" + secret + "x" * 4000})
        return SimpleNamespace(status_code=200, json=lambda: {"to_state": "EXTERNAL_INGEST_BLOCKED"})
    queue = controller_client.ControllerQueue(SimpleNamespace(request=request),
        base_url="http://test", auth=("claudecode", "test"), agent="claudecode")
    monkeypatch.setattr(queue, "heartbeat", lambda *a: {"hard_deadline_seconds_remaining": 30})
    monkeypatch.setattr(ingest, "ingest", lambda *a, **k: {"registered": "evidence"})
    ingest.execute_ingest(activation(), queue)
    assert len(calls) == expected
    assert calls[0]["outcome"] == "registered"
    if status == 422:
        assert calls[1]["outcome"] == "blocked"
        assert calls[1]["payload"]["reason_code"] == "worker_error"
        detail = calls[1]["payload"]["detail"]
        assert "422" in detail and len(detail) <= 2000 and secret not in detail
        detail.encode("utf-8")


def test_fallback_refusal_does_not_recurse(monkeypatch):
    calls = []
    def report(aid, **kw):
        calls.append(kw)
        raise controller_client.Refused("invalid", status_code=422, detail="invalid")
    queue = SimpleNamespace(report_ingest=report,
        heartbeat=lambda *a: {"hard_deadline_seconds_remaining": 30})
    monkeypatch.setattr(ingest, "ingest", lambda *a, **k: {})
    ingest.execute_ingest(activation(), queue)
    assert [c["outcome"] for c in calls] == ["registered", "blocked"]


