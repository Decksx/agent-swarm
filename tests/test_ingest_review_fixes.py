def test_child_environment_drops_worker_secrets_and_git_overrides(tmp_path, monkeypatch):
    forbidden = ["HUB_SECRET", "CLAUDE_HUB_SECRET", "OPENAI_API_KEY", "GIT_DIR",
                 "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_CONFIG_COUNT", "GIT_SSH_COMMAND"]
    for name in forbidden:
        monkeypatch.setenv(name, "private-test-value")
    monkeypatch.setenv("GH_TOKEN", "test-gh-auth")
    code = "import os,json; print(json.dumps({k:os.environ.get(k) for k in " + repr(forbidden + ["GH_TOKEN"]) + "}))"
    result = ingest.Commands(10, lambda: True).run([sys.executable, "-c", code], tmp_path)
    values = json.loads(result[1])
    assert all(values[name] is None for name in forbidden)
    assert values["GH_TOKEN"] == "test-gh-auth"


def test_heartbeat_is_throttled_but_deadline_is_checked_every_time(monkeypatch):
    clock, beats = [100.0], []
    monkeypatch.setattr(ingest.time, "monotonic", lambda: clock[0])
    command = ingest.Commands(60, lambda: beats.append(clock[0]) or True)
    for _ in range(100):
        command.checkpoint()
    assert beats == [100.0]
    clock[0] = 116.0
    command.checkpoint()
    assert beats == [100.0, 116.0]
    command.deadline = 115.0
    with pytest.raises(ingest.IngestError, match="deadline_exhausted"):
        command.checkpoint()


@pytest.mark.parametrize("diagnostic,exit_code,code", [
    ("authentication required", 4, "gh_auth"),
    ("HTTP 401 private-token", 1, "gh_auth"),
    ("HTTP 404 not found", 1, "not_found"),
    ("dial tcp: no such host", 1, "github_unreachable"),
    ("HTTP 500 internal error", 1, "gh_error"),
])
def test_gh_error_codes_use_observed_transport_cause_only(tmp_path, monkeypatch, diagnostic, exit_code, code):
    original = subprocess.Popen
    def spawn(args, **kwargs):
        script = "import sys; sys.stderr.write(" + repr(diagnostic) + "); sys.exit(" + str(exit_code) + ")"
        return original([sys.executable, "-c", script], **kwargs)
    monkeypatch.setattr(ingest.subprocess, "Popen", spawn)
    with pytest.raises(ingest.IngestError) as exc:
        ingest.Commands(10, lambda: True).run(["gh", "api", "repos/owner/repo"], tmp_path)
    assert exc.value.code == code and diagnostic not in str(exc.value.facts)
